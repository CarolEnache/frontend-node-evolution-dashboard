export function isSourceCatalogEntry(entry: Pick<Entry, "raw">): boolean {
  return Boolean(
    entry.raw &&
      typeof entry.raw === "object" &&
      "sourceCatalog" in entry.raw &&
      (entry.raw as { sourceCatalog?: unknown }).sourceCatalog === true,
  );
}

